SAVESYM	PROC	NEAR	; DS:SI=Symbol name pointer, AX=Number
	MOV	BP,AX
	MOV	DI,OFFSET SYMTAB
	MOV	CX,SYMS
	OR	CX,CX
	CLD
	JZ	SAVESYM_EMPTY
SAVESYM_L0:
	PUSH	SI
	PUSH	DI
	PUSH	CX
	MOV	CX,SYMLEN
SAVESYM_VERIFY:
	LODSB
	CMP	AL,33
	JNC	SAVESYM_CHAR
	XOR	AL,AL
	DEC	SI
SAVESYM_CHAR:
	CMP	AL,[DI]
	JNZ	SAVESYM_NEQ
SAVESYM_EQ:
	INC	DI
	LOOP	SAVESYM_VERIFY
	POP	CX
	POP	DI
	POP	SI
	MOV	SI,OFFSET M_DUPDEF
	CALL	MSG
	STC
	RET

SAVESYM_NEQ:
	POP	CX
	POP	DI
	POP	SI
	ADD	DI,SYMLEN+2
	LOOP	SAVESYM_L0
SAVESYM_EMPTY:
	INC	SYMS
	MOV	CX,SYMLEN
SAVESYM_SAVE:
	LODSB
	CMP	AL,33
	JNC	SAVESYM_OK
	DEC	SI
	XOR	AL,AL
SAVESYM_OK:
	MOV	[DI],AL
	INC	DI
	LOOP	SAVESYM_SAVE
	MOV	AX,BP
	MOV	[DI],AX
	CLC
	RET
SAVESYM	ENDP

