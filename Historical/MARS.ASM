GETPARAM	PROC	NEAR
	MOV	AL,QQ
	PUSH	AX
	CMP	AL,'+'
	JZ	GETPARAM_1SKIP
	CMP	AL,'-'
	JNZ	GETPARAM_0SKIP
GETPARAM_1SKIP:
	CALL	RC
GETPARAM_0SKIP:
	CALL	GETANY
	POP	CX
	JC	GETPARAM_TO_ERROR
	CMP	CL,'-'
	JNZ	GETPARAM_POS
	NEG	AX
GETPARAM_POS:
	MOV	BP,AX
GETPARAM_LOOP:
	MOV	AL,QQ
	CMP	AL,33
	JC	GETPARAM_END
	CMP	AL,'+'
	JZ	GETPARAM_ADD
	CMP	AL,'-'
	JZ	GETPARAM_SUB
	CMP	AL,'*'
	JZ	GETPARAM_MUL
	CMP	AL,'/'
	JZ	GETPARAM_DIV
	CMP	AL,'%'
	JZ	GETPARAM_DIVR
GETPARAM_TO_ERROR:
	JMP	GETPARAM_ERROR

GETPARAM_END:
	MOV	AX,BP
	MODULO	AX
	CLC
	RET

GETPARAM_ADD:
	CALL	RC
	CALL	GETANY
	ADD	BP,AX
	JMP	GETPARAM_BACK

GETPARAM_SUB:
	CALL	RC
	CALL	GETANY
	SUB	BP,AX
	JMP	GETPARAM_BACK

GETPARAM_MUL:
	CALL	RC
	CALL	GETANY
	IMUL	BP
	MOV	BP,AX
	JMP	GETPARAM_BACK

GETPARAM_DIV:
	CALL	RC
	CALL	GETANY
	XCHG	AX,BP
	XOR	DX,DX
	OR	BP,BP
	JZ	GETPARAM_DIVZERO
	IDIV	BP
	MOV	BP,AX
	JMP	GETPARAM_BACK

GETPARAM_DIVR:
	CALL	RC
	CALL	GETANY
	XCHG	AX,BP
	XOR	DX,DX
	OR	BP,BP
	JZ	GETPARAM_DIVZERO
	IDIV	BP
	MOV	BP,DX
	JMP	GETPARAM_BACK

GETPARAM_DIVZERO:
	MOV	SI,OFFSET M_DIVZERO
	CALL	MSG
	XOR	BP,AX
	MOV	BP,7FFFH
	JNS	GETPARAM_BACK
	NEG	BP
GETPARAM_BACK:
	JMP	GETPARAM_LOOP

GETPARAM_ERROR:
	CALL	RCSPACE
	XOR	AX,AX
	STC
	RET
GETPARAM	ENDP

