READBYTE	PROC	NEAR
	XOR	AX,AX
	CMP	AX,PREDATA
	JNZ	READBYTE_OK
	CMP	AX,FEOF
	JNZ	READBYTE_QUIT
	PUSH	BX
	PUSH	CX
	PUSH	DX
	PUSH	SI
	PUSH	DI
	PUSH	BP
	PUSH	ES
	MOV	DX,OFFSET PREREAD
	MOV	PREPTR,DX
	MOV	CX,PRERDLEN
	MOV	BX,HANDLE
	MOV	AH,3FH
	INT	21H
	JC	READBYTE_ERROR
	MOV	PREDATA,AX
	CMP	AX,PRERDLEN
	MOV	AX,0
	RCL	AX,1
	MOV	FEOF,AX
	CLC
READBYTE_ERROR:
	POP	ES
	POP	BP
	POP	DI
	POP	SI
	POP	DX
	POP	CX
	POP	BX
	JNC	READBYTE
	RET

READBYTE_OK:
	PUSH	SI
	MOV	SI,PREPTR
	CLD
	LODSB
	MOV	PREPTR,SI
	DEC	PREDATA
	POP	SI
READBYTE_QUIT:
	CMP	AL,80H
	JNC	READBYTE_SPACE
	CMP	AL,0DH
	JZ	READBYTE_SKIP
	OR	AL,AL
	JZ	READBYTE_SKIP
	CMP	AL,32
	JNC	READBYTE_SKIP
READBYTE_SPACE:
	MOV	AL,32
READBYTE_SKIP:
	TOUPPER	AL
	CLC
	RET
READBYTE	ENDP	; AH=0, AL=Readed character (0 on eof), CF=Error

