ENTRY     PROC      NEAR
	MOV	SP,OFFSET STACKEND
	MOV	AX,3
	INT	10H
	MOV	AX,CS
	MOV	DS,AX
	MOV	SI,OFFSET OPENMSG
	CALL	MSG
	MOV	AX,OFFSET PROGEND
	ADD	AX,15
	SHR	AX,4
	MOV	BX,CS
	MOV	DS,BX
	ADD	AX,BX
	MOV	FIRSTSEG,AX
	MOV	CURRSEG,AX
	CALL	RANDOMIZE
	CALL	RESETPROG
	XOR	CX,CX
	MOV	ERRORS,CX
LOOP0:
	CALL	GETPROG
	JC	SKIP0
	MOV	AX,CS
	MOV	DS,AX
	MOV	AX,CURRSEG
	MOV	ES,AX
	ADD	AX,(SIZE PROGDATA+15)/16
	MOV	CURRSEG,AX
	MOV	BX,DS:[2]
	SUB	BX,1000H
	CMP	AX,BX
	JNC	MEMORY_ERROR
	PUSH	CX
	PUSH	DS
	PUSH	ES
	MOV	SI,OFFSET NEXTNAME
	CALL	INITPROGD
	CALL	COMPILE
	POP	ES
	POP	DS
	POP	CX
	INC	CX
	JMP	LOOP0

SKIP0:
	OR	CX,CX
	JZ	NOPROG_ERROR
	XOR	AX,AX
	MOV	ES:[0].NEXTOFF,AX
	MOV	AX,FIRSTSEG
	MOV	ES:[0].NEXTSEG,AX
	MOV	NPROG,CX
	MOV	NPROG0,CX
	MOV	AX,CURRSEG
	MOV	ARENASEG,AX
	CMP	ERRORS,0
	JNZ	ERRORS_ERROR
	MOV	AX,WARLENL
	MOV	BX,WARLENH
	MOV	WARLENLB,AX
	MOV	WARLENHB,BX
	MOV	AX,13H
	INT	10H
	CALL	WAR
QUIT:
	XOR	AX,AX
	MOV	DS,AX
	AND	WORD PTR DS:[0417H],0FCF0H
	MOV	AX,4C00H
	INT	21H

MEMORY_ERROR:
	MOV	SI,OFFSET M_MEMORY
	CALL	MSG
	JMP	QUIT

ERRORS_ERROR:
	MOV	SI,OFFSET M_ERRORS
	CALL	MSG
	JMP	QUIT

NOPROG_ERROR:
	MOV	SI,OFFSET M_NOPROG
	CALL	MSG
	JMP	QUIT
ENTRY     ENDP

