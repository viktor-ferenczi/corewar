PARAMX	PROC	NEAR	; File queue = the begining of the parameter
	PUSH	AX
PARAMX_SEARCH:
	CMP	QQ,32
	JNZ	PARAMX_SS
	CALL	RC
	JMP	PARAMX_SEARCH

PARAMX_SS:
	POP	AX
	MOV	AH,QQ
	TEST	AL,PARAM_CAN
	JZ	PARAMX_SKIP
	TEST	AL,PARAM_MST
	JZ	PARAMX_S0
	CMP	AH,';'
	JZ	PARAMX_MISSING
	CMP	AH,33
	JNC	PARAMX_S0
PARAMX_MISSING:
	MOV	SI,OFFSET M_MISSOP
	CALL	MSG
	XOR	AX,AX
	MOV	BX,AX
	STC
	RET

PARAMX_S0:
	CMP	AH,';'
	JZ	PARAMX_SKIP
	MOV	SI,OFFSET QQ+1
	CMP	AH,33
	JC	PARAMX_SKIP
	XOR	BL,BL
	MOV	BH,AL
	ROL	BH,2
	AND	BH,3
	CMP	AH,'#'
	JZ	PARAMX_OK
	INC	BL
	CMP	AH,'$'
	JZ	PARAMX_OK
	INC	BL
	CMP	AH,'@'
	JZ	PARAMX_OK
	INC	BL
	CMP	AH,'<'
	JZ	PARAMX_OK
	MOV	BL,BH
	DEC	SI
PARAMX_OK:
	CMP	SI,OFFSET QQ
	JZ	PARAMX_OKS
	CALL	RC
	DEC	SI
PARAMX_OKS:
	MOV	CL,BL
	INC	CL
	ROR	AL,CL
	JNC	PARAMX_NOTALLOW
	PUSH	BX
	CALL	GETPARAM
	JNC	PARAMX_NOERROR
	POP	BX
	MOV	SI,OFFSET M_PARERR
	JMP	PARAMX_ERRMSG

PARAMX_NOERROR:
	PUSHF
	CALL	RCSPACE
	POPF
	POP	BX
	AND	BX,3
	RET

PARAMX_SKIP:
	XOR	AX,AX
	MOV	BX,4
	RET

PARAMX_NOTALLOW:
	MOV	SI,OFFSET M_ILLPAR
PARAMX_ERRMSG:
	CALL	MSG
	XOR	AX,AX
	MOV	BX,AX
	STC
	RET	
PARAMX	ENDP		; CF=1 error
			; AX=Parameter equal
 			; BL=Addressing mode

